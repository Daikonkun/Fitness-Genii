import assert from 'node:assert/strict';
import {loadTypeScriptModule as load} from './lib/load-typescript.mjs';
const {equipmentConfigSchema,serializeEquipment,readEquipmentConfig,emptyEquipment,configAllows,loadCaption,hasGeneratedLoad}=load('src/lib/equipmentConfig.ts');
const {exercises}=load('src/lib/exercises/catalogue.ts');
const {bandEquipmentCompatible,missingKitFocus}=load('src/lib/exercises/equipment.ts');
const find=id=>exercises.find(e=>e.id===id);
const body=emptyEquipment();
assert.deepEqual(readEquipmentConfig(serializeEquipment(body)),body);
for(const invalid of ['equipment:v1:{bad','equipment:v2:{}','equipment:v1:{}']) assert.equal(readEquipmentConfig(invalid),null);
const one={...body,selected:['dumbbells'],primary:'dumbbells',dumbbells:{weight:5,unit:'kg',count:1}};
assert.ok(equipmentConfigSchema.safeParse(one).success);
assert.ok(configAllows(find('goblet-squat'),one));
assert.ok(!configAllows(find('dumbbell-floor-press'),one));
assert.ok(!configAllows(find('supported-dumbbell-row'),one));
assert.ok(configAllows(find('supported-dumbbell-row'),{...one,supports:{chair:true,wall:false}}));
for(const weight of [0,-5,Infinity,NaN,501]) assert.equal(equipmentConfigSchema.safeParse({...one,dumbbells:{...one.dumbbells,weight}}).success,false);
for(const text of ['Use 5kg','use 10 lb','五公斤','2磅','use heavier dumbbells','increase resistance']) assert.ok(hasGeneratedLoad(text),text);
assert.equal(hasGeneratedLoad('3 sets × 10 reps, 60 sec rest'),false);
const kit={...body,selected:['kit','bodyweight'],primary:'kit',kit:{rating:6,unit:'kg',basis:'unknown',tubesPerSide:2}};
assert.ok(loadCaption(find('handled-tube-curl'),kit).includes('basis unspecified'));
assert.equal(bandEquipmentCompatible(find('band-pull-apart'),serializeEquipment(kit)),false);
assert.equal(bandEquipmentCompatible(find('innstar-bar-floor-press'),serializeEquipment(kit)),true);
assert.deepEqual(missingKitFocus(exercises.filter(e=>configAllows(e,kit)),serializeEquipment(kit)),[]);
const gym={...one,selected:['full_gym'],primary:'full_gym',dumbbells:{weight:10,unit:'lb',count:2}};
assert.ok(configAllows(find('dumbbell-floor-press'),gym));
assert.ok(!configAllows(find('innstar-bar-floor-press'),gym));
assert.ok(!configAllows(find('wall-push-up'),gym));
assert.ok(!equipmentConfigSchema.safeParse({...gym,primary:'kit'}).success);
assert.ok(!equipmentConfigSchema.safeParse({...body,selected:[]}).success);
console.log('Equipment selection, quantity, units, validation and compatibility passed.');
